/**
 * Developer-run generator: economy.config.json -> the two typed mirrors, so
 * the server (authoritative) and the app (display) read the SAME numbers and
 * cannot drift. Same pattern as scripts/gen-avatar-catalog.mjs.
 *
 *   server/src/economy.generated.ts
 *   src/lib/economy.generated.ts
 *
 * Usage (repo root): node scripts/gen-economy.mjs   (then check-economy.mjs)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const cfg = JSON.parse(readFileSync(join(ROOT, 'economy.config.json'), 'utf8'));
const { _readme, ...config } = cfg;
delete config.incomeModel._note;
delete config.fame._note;
delete config.tour._note;

const price = (tier) => {
  if (tier === null) return { gems: 0, chips: 0 };
  const t = cfg.tiers[tier];
  if (!t) throw new Error(`unknown tier: ${tier}`);
  return { gems: t.gems, chips: t.gemsOnly ? null : t.gems * cfg.gemToChip };
};
const cosmeticPrices = {};
for (const group of [cfg.boards, cfg.pieces]) {
  for (const [id, tier] of Object.entries(group)) cosmeticPrices[id] = price(tier);
}

// Level rewards expanded to one entry per level (chips from the per-level ranges plus
// the milestone extras), so server and client share one lookup table.
const levelRewards = {};
for (const range of cfg.levels.chipsPerLevel) {
  for (let level = range.from; level <= range.to; level++) levelRewards[level] = { chips: range.chips, gems: 0 };
}
for (const [level, extra] of Object.entries(cfg.levels.milestones)) {
  const base = levelRewards[level] ?? { chips: 0, gems: 0 };
  levelRewards[level] = { chips: base.chips + (extra.chips ?? 0), gems: base.gems + (extra.gems ?? 0) };
}

const banner = '// GENERATED by scripts/gen-economy.mjs from economy.config.json -- do not edit by hand.\n';
const body =
  `export const ECONOMY = ${JSON.stringify(config, null, 2)} as const;\n\n` +
  `// gems/chips per board + piece-set id (chips = gems x ECONOMY.gemToChip).\n` +
  `export const COSMETIC_PRICES: Record<string, { gems: number; chips: number | null }> = ${JSON.stringify(cosmeticPrices, null, 2)};\n\n` +
  `// Per-level reward (chips/gems) credited once when a player reaches the level.\n` +
  `export const LEVEL_REWARDS: Record<number, { chips: number; gems: number }> = ${JSON.stringify(levelRewards, null, 2)};\n\n` +
  `export type BotRewardDifficulty = keyof typeof ECONOMY.matchRewards.botWin;\n`;

writeFileSync(join(ROOT, 'server', 'src', 'economy.generated.ts'), banner + body);
writeFileSync(join(ROOT, 'src', 'lib', 'economy.generated.ts'), banner + body);
console.log('Wrote economy.generated.ts (server + client).');
