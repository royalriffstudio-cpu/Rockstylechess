/**
 * Developer-run generator: the app's bot code -> the server, so a Festival set played against a
 * SERVER-hosted bot is the same opponent the player sees in a normal bot game. Same pattern as
 * gen-economy.mjs: edit the source, re-run, commit the output.
 *
 *   src/lib/heuristicBot.ts            -> server/src/bots/heuristicBot.generated.ts
 *   STOCKFISH_PRESETS (botEngine.ts)   -> server/src/bots/presets.generated.ts
 *   stockfish-18-lite-single.{js,wasm} -> server/vendor/stockfish/  (the SAME build the app embeds)
 *
 * Usage (repo root): node scripts/gen-server-bots.mjs
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const banner = '// GENERATED by scripts/gen-server-bots.mjs -- do not edit by hand.\n';
const outDir = join(ROOT, 'server', 'src', 'bots');
mkdirSync(outDir, { recursive: true });

const heuristic = readFileSync(join(ROOT, 'src', 'lib', 'heuristicBot.ts'), 'utf8');
const importLine = "import type { EngineMove } from './botEngine';";
if (!heuristic.includes(importLine)) throw new Error('heuristicBot.ts import changed; update gen-server-bots.mjs');
writeFileSync(join(outDir, 'heuristicBot.generated.ts'), banner + heuristic.replace(importLine, "import type { EngineMove } from './types.js';"));

const engine = readFileSync(join(ROOT, 'src', 'lib', 'botEngine.ts'), 'utf8');
const presets = engine.match(/export const STOCKFISH_PRESETS[^=]*=\s*(\{[\s\S]*?\n\});/);
if (!presets) throw new Error('STOCKFISH_PRESETS not found in botEngine.ts');
writeFileSync(
  join(outDir, 'presets.generated.ts'),
  `${banner}export interface StockfishConfig {\n  depth: number;\n  movetimeMs: number;\n}\n\nexport const STOCKFISH_PRESETS: Record<'stockfish-basic' | 'stockfish-lite' | 'stockfish-strong', StockfishConfig> = ${presets[1]};\n`,
);

const vendorSrc = join(ROOT, 'node_modules', 'stockfish');
const vendorOut = join(ROOT, 'server', 'vendor', 'stockfish');
mkdirSync(vendorOut, { recursive: true });
for (const f of ['stockfish-18-lite-single.js', 'stockfish-18-lite-single.wasm']) copyFileSync(join(vendorSrc, 'bin', f), join(vendorOut, f));
copyFileSync(join(vendorSrc, 'Copying.txt'), join(vendorOut, 'Copying.txt'));
// server/package.json is "type": "module"; the vendor build is CommonJS.
writeFileSync(join(vendorOut, 'package.json'), '{ "type": "commonjs" }\n');
console.log('Wrote server/src/bots/*.generated.ts and server/vendor/stockfish/.');
